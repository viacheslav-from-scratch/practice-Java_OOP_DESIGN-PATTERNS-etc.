public class Printer {
    public void print(int text){
        System.out.println("Printing..." + "\n" +
                "You are printed this: " + text);
    }
    public void print(double text){
        System.out.println("Printing..." + "\n" +
                "You are printed this: " + text);
    }
    public void print(String text){
        System.out.println("Printing..." + "\n" +
                "You are printed this: " + text);
    }
    public void print(char text){
        System.out.println("Printing..." + "\n" +
                "You are printed this: " + text);
    }
}
